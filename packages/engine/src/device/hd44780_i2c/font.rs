//! The Hitachi HD44780U ROM Code A00 5×8 character generator (ADE-207-272 Table 4) and
//! its Unicode mapping for reading visible text.
//!
//! Each glyph is eight rows, top to bottom, with bits 4 down to 0 left to right.
//! Codes `0x00..=0x07` (mirrored at `0x08..=0x0F`) come from CGRAM rather than ROM.

/// Returns the 5×8 bitmap for character code `code`, reading `cgram` (64 bytes, 8 glyphs × 8 rows)
/// for codes `0x00..=0x0F` and the A00 ROM for `0x10..=0xFF`.
pub fn glyph(code: u8, cgram: &[u8]) -> [u8; 8] {
    if code < 0x10 {
        let slot = usize::from(code & 0x07) * 8;
        let mut rows = [0u8; 8];
        for (i, row) in rows.iter_mut().enumerate() {
            *row = cgram.get(slot + i).copied().unwrap_or(0) & 0x1f;
        }
        return rows;
    }
    A00_ROM[usize::from(code)]
}

/// Maps an HD44780 A00 ROM character code to one visible Unicode character, so a 16-column
/// row always reads back as 16 characters.
///
/// CGRAM slots `0x00..=0x0F` map to `□` (U+25A1). Blank ROM slots (`0x10..=0x1F`, `0x80..=0xA0`,
/// `0xFE`) map to a space.
pub fn char_for(code: u8) -> char {
    match code {
        0x00..=0x0f => '□',
        0x10..=0x1f | 0x80..=0xa0 | 0xfe => ' ',
        0x5c => '¥',
        0x7e => '→',
        0x7f => '←',
        0x20..=0x7d => char::from(code),
        0xa1..=0xdf => char::from_u32(0xff61 + u32::from(code - 0xa1)).unwrap_or(' '),
        0xe0 => 'α',
        0xe1 => 'ä',
        0xe2 => 'β',
        0xe3 => 'ε',
        0xe4 => 'μ',
        0xe5 => 'σ',
        0xe6 => 'ρ',
        0xe7 => 'g',
        0xe8 => '√',
        0xe9 => '⁻',
        0xea => 'j',
        0xeb => 'ˣ',
        0xec => '¢',
        0xed => '£',
        0xee => 'ñ',
        0xef => 'ö',
        0xf0 => 'p',
        0xf1 => 'q',
        0xf2 => 'θ',
        0xf3 => '∞',
        0xf4 => 'Ω',
        0xf5 => 'ü',
        0xf6 => 'Σ',
        0xf7 => 'π',
        0xf8 => 'x',
        0xf9 => 'y',
        0xfa => '千',
        0xfb => '万',
        0xfc => '円',
        0xfd => '÷',
        0xff => '█',
    }
}

